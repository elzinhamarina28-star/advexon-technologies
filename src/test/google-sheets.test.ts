import { describe, expect, it, vi } from 'vitest';
import { decryptToken, handleSheetsOperation } from '@/features/integrations/google-sheets.server';
import { encryptToken } from '@/features/integrations/google-oauth.server';

const key = btoa(String.fromCharCode(...new Uint8Array(32).fill(19)));
function deps(over: Record<string, unknown> = {}) {
  return {
    verifyUser: vi.fn(async (token: string) => token === 'good' ? 'user-1' : null),
    getConnection: vi.fn(async () => null),
    saveTokens: vi.fn(async () => true),
    fetch: vi.fn(async () => Response.json({ values: [['A1']] })),
    now: () => 1_800_000_000_000,
    ...over,
  } as any;
}
function request(body: unknown, token = 'good') {
  return new Request('https://x.test/api/integrations/google/sheets', {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: 'Bearer ' + token },
    body: JSON.stringify(body),
  });
}
describe('Google Sheets operations', () => {
  it('requires authentication', async () => {
    expect((await handleSheetsOperation(request({ operation: 'read' }, ''), deps())).status).toBe(401);
    expect((await handleSheetsOperation(request({ operation: 'read' }, 'bad'), deps())).status).toBe(401);
  });
  it('rejects malformed spreadsheet ids and ranges', async () => {
    expect((await handleSheetsOperation(request({ operation: 'read', spreadsheetId: 'short', range: 'A1' }), deps())).status).toBe(400);
    expect((await handleSheetsOperation(request({ operation: 'read', spreadsheetId: 'abcdefghijklmnopqrst', range: 'A1\nB2' }), deps())).status).toBe(400);
  });
  it('rejects unsupported operation and unsafe write payloads', async () => {
    const d = deps();
    expect((await handleSheetsOperation(request({ operation: 'delete', spreadsheetId: 'abcdefghijklmnopqrst', range: 'A1' }), d)).status).toBe(400);
    expect((await handleSheetsOperation(request({ operation: 'write', spreadsheetId: 'abcdefghijklmnopqrst', range: 'A1', values: 'not an array' }), d)).status).toBe(400);
    expect(d.fetch).not.toHaveBeenCalled();
  });
  it('reports disconnected account without calling Google', async () => {
    const d = deps();
    const response = await handleSheetsOperation(request({ operation: 'read', spreadsheetId: 'abcdefghijklmnopqrst', range: 'Sheet1!A1:B5' }), d);
    expect(response.status).toBe(409);
    expect(d.fetch).not.toHaveBeenCalled();
  });
  it('decrypts only valid ciphertext generated by AES-GCM', async () => {
    const encrypted = await encryptToken('access-token', key);
    expect(await decryptToken(encrypted, key)).toBe('access-token');
    await expect(decryptToken(encrypted, btoa('wrong'))).rejects.toThrow();
  });
});
